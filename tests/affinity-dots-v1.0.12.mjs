// Testes da UI de Afinidades: três bolinhas e cadastro sem lista de fichas.
import assert from 'node:assert/strict';
import { affinityView, nextAffinityLevel, normalizeAffinityData, describeAffinityGroups,
  updateAffinityValue, createJournalAffinity } from '../module/affinity-journals.mjs';
const owner={id:'owner',isGM:false};
const hidden={id:'secret',name:'Grande vilão futuro',type:'personagem',img:'secret.png',testUserPermission(){return false;}};
const leader={id:'a1',name:'Mason',type:'personagem',img:'mason.png',testUserPermission(){return true;}};
const ally={id:'a2',name:'Uri',type:'personagem',img:'uri.png',testUserPermission(){return true;}};
const actors=[leader,ally,hidden];
const party={schema:1,parties:[{id:'p',name:'Escolhidos',memberIds:['a1','a2']}]};
let storage={schema:1,entries:[{key:'actor:a2',name:'',afeicao:2,admiracao:1},{key:'actor:secret',name:'',afeicao:3,admiracao:3},{key:'npc:friend',name:'Taverneira',afeicao:3,admiracao:0}]};
const journal={id:'j1',name:'Diário — Mason',pack:null,getFlag(scope,key){if(key==='affinitiesV1')return storage;if(key==='autoDiaryActorId')return leader.id;},testUserPermission(){return true;},async setFlag(scope,key,value){storage=structuredClone(value);}};
leader.getFlag=(_,key)=>key==='autoDiaryJournalId'?journal.id:null;
const journals=[journal];
globalThis.game={user:owner,actors:{get:id=>actors.find(a=>a.id===id),contents:actors},journal:{get:id=>journals.find(j=>j.id===id),contents:journals},settings:{get:()=>party}};
const html=affinityView(leader,journal);
assert.match(html,/Membros da equipe/);
assert.match(html,/Taverneira/);
assert.match(html,/data-mv-aff-name/);
assert.doesNotMatch(html,/<select\b/);
assert.doesNotMatch(html,/data-mv-aff-actor/);
assert.doesNotMatch(html,/Grande vilão futuro/);
assert.doesNotMatch(html,/secret\.png/);
assert.equal((html.match(/class="mv-aff-dot(?: is-active)?"/g)||[]).length,12, '2 visible relationships × 2 fields × 3 dots');
assert.equal((html.match(/mv-aff-affection/g)||[]).length,2);
assert.equal((html.match(/mv-aff-admiration/g)||[]).length,2);
assert.equal((html.match(/aria-pressed="true"/g)||[]).length,3, 'seleções finais marcadas com aria-pressed');
assert.equal(nextAffinityLevel(0,1),1);
assert.equal(nextAffinityLevel(1,1),0);
assert.equal(nextAffinityLevel(3,1),1);
assert.equal(nextAffinityLevel(3,3),0);
assert.equal(nextAffinityLevel(0,3),3);
assert.throws(()=>nextAffinityLevel(0,4),/0 a 3/);
assert.throws(()=>updateAffinityValue(null,'actor:a2','afeicao',-1),/0 a 3/);
assert.throws(()=>updateAffinityValue(null,'actor:a2','admiracao',4),/0 a 3/);
assert.equal(updateAffinityValue(null,'actor:a2','afeicao',3).entries[0].afeicao,3);
const legacy=normalizeAffinityData({entries:[{key:'actor:a2',afeicao:-2,admiracao:5}]});
assert.equal(legacy.entries[0].afeicao,-2, 'dados antigos negativos não podem ser sobrescritos');
assert.equal(legacy.entries[0].admiracao,5, 'dados antigos acima de 3 não podem ser sobrescritos');
const withLegacy={...journal,getFlag(scope,key){return key==='affinitiesV1'?legacy:journal.getFlag(scope,key);}};
const renderedLegacy=affinityView(leader,withLegacy);
assert.match(renderedLegacy,/Valor antigo fora da escala/);
assert.doesNotMatch(renderedLegacy,/type="number"/);
const groups=describeAffinityGroups(leader,storage,['a2']);
assert.equal(groups.others.length,1,'personagem oculto não deve aparecer em outros relacionamentos');
await createJournalAffinity(journal,{name:'Viajante desconhecido',makeId:()=>'newid'});
assert.ok(storage.entries.find(e=>e.name==='Viajante desconhecido'));
assert.equal(storage.entries.some(e=>e.name==='Grande vilão futuro'),false);
console.log('OK: bolinhas de 0 a 3, clique para zerar, ausência de seletor e spoilers, salvamento e legado preservado.');
