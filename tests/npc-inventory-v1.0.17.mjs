import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const base=path.resolve(import.meta.dirname,'..');
const read=f=>fs.readFileSync(path.join(base,f),'utf8');
const manifest=JSON.parse(read('system.json'));
const template=read('templates/npc.hbs');
const sheet=read('module/npc-sheet.mjs');
const inventory=read('module/inventory-ui.mjs');
const css=read('styles/npc-v1.0.18.css');
assert.ok(['1.0.18','1.0.19','1.0.20'].includes(manifest.version));
assert.ok(manifest.styles.includes('styles/npc-v1.0.18.css'));
assert.ok(template.includes('data-npc-tab="inventario"'));
assert.ok(template.includes('data-npc-panel="inventario" hidden'));
assert.ok(template.includes('data-mv-inventory-mount'));
assert.ok(template.includes('multiverso-personagem mv-npc-inventory-host'));
assert.ok(template.includes('{{#if canEdit}}<button type="button" data-npc-tab="inventario"'));
assert.ok(template.indexOf('data-npc-tab="combate"')<template.indexOf('data-npc-tab="inventario"'));
assert.ok(template.indexOf('data-npc-tab="inventario"')<template.indexOf('data-npc-tab="relacionamentos"'));
assert.ok(sheet.includes("import {bindInventoryUI} from './inventory-ui.mjs'"));
assert.ok(sheet.includes("if(canEdit && !(this instanceof MultiversoNPCCreationSheet)) bindInventoryUI(this,root)"));
assert.ok(sheet.includes("['combate','inventario','apoio','relacionamentos']"));
assert.ok(css.includes('.mv-npc-panel[data-npc-panel="inventario"] {display:none!important;}'));
assert.ok(inventory.includes("const isNPC=actor.type==='npc'"));
assert.ok(inventory.includes("actor.system?.forcanumero"));
for(const k of ['data-mv-inv-create','data-mv-inv-use','data-mv-inv-cast','data-mv-inv-transfer','data-mv-inv-toggle-equip','data-mv-inv-discard','data-mv-inv-currency-add'])assert.ok(inventory.includes(k));
assert.ok(inventory.includes("actor.createEmbeddedDocuments('Item'"));
assert.ok(inventory.includes("useItemMotor(item,{operationMode:'cast'})"));
// Os outros recursos continuam no documento e sem alteração do sistema de itens.
for(const k of ['data-npc-panel="combate"','data-npc-panel="relacionamentos"','data-npc-panel="apoio"','data-npc-panel="criacao"'])assert.ok(template.includes(k));
assert.ok(sheet.includes('npcRelationGroups'));
assert.ok(sheet.includes('executeNativeEffectTest'));
assert.ok(inventory.includes("const equipment = actor => Array.from(actor.items ?? []).filter(i => i.type === 'equipamento')"));
console.log('OK: v1.0.17 — inventário nativo do NPC, aba GM, criação/uso/equipar/transferência, cabeçalho NPC e motor preservados.');
