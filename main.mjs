import {registerOpenEffectChat} from './module/open-effect-chat.mjs';
import {registerExternalResistanceChat} from './module/external-resistance-chat.mjs';
import {registerFireConditions} from "./module/fire-conditions.mjs";
import {registerAreaMovement} from "./module/area-movement.mjs";
import {registerItemMotor} from './module/item-motor.mjs';
import {registerReactionCombat} from "./module/reaction-combat.mjs";
import {registerCombatNativeUi} from "./module/combat-native-ui.mjs";
import {registerPersistentAreas} from "./module/persistent-areas.mjs";
import {registerAdvancedMotor} from "./module/advanced-motor.mjs";
import {registerMultiTarget} from "./module/multi-target.mjs";
import {registerOpposedChat} from "./module/opposed-chat.mjs";
import {registerTemporaryResource} from "./module/temporary-resource.mjs";
import {registerTemporaryPv} from "./module/temporary-pv.mjs";
import {registerChatRollApply} from "./module/chat-roll-apply.mjs";
import {registerActionRestrictionWarnings} from "./module/action-restrictions.mjs";
import {registerDurationTracking} from "./module/effect-tracking.mjs";
import {registerExternalCardApply} from "./module/external-card-apply.mjs";
import {registerEffectChatCards} from "./module/effect-chat.mjs";
import {registerUsageEvents} from "./module/skill-uses.mjs";
import {registerCombatTools} from "./module/combat-tools.mjs";
import {PersonagemData, MultiversoItemData} from "./module/data-models.mjs";
import {MultiversoItemSheet} from "./module/item-sheet.mjs";
import {MultiversoPersonagemSheet} from "./module/personagem-sheet.mjs";
Hooks.once("init", () => {
  registerPartyManager();
  registerAutoDiaries();
  registerDiaryManager();
  registerAffinityJournals();
  registerEffectChatCards();
  registerExternalResistanceChat();
  registerOpenEffectChat();
  registerExternalCardApply();
  registerMultiTarget();
  registerOpposedChat();
  registerChatRollApply();
  registerTemporaryPv();
  registerTemporaryResource();
  registerDurationTracking();
  registerUsageEvents();
  registerCombatTools();
  registerItemMotor();
  registerReactionCombat();
  registerCombatNativeUi();
  registerAdvancedMotor();
  registerPersistentAreas();
  registerAreaMovement();
  registerFireConditions();
  registerActionRestrictionWarnings();
  CONFIG.Actor.dataModels.personagem = PersonagemData;
  CONFIG.Actor.dataModels.npc = NPCData;
  registerNPCInitialization();
  for (const type of ["equipamento","skill","tecnica","classe","subclasse","especie","habilidadeClasse","habilidadeSubclasse","habilidadeEspecie","vantagem"]) {
    CONFIG.Item.dataModels[type] = MultiversoItemData;
  }
  foundry.applications.apps.DocumentSheetConfig.registerSheet(Item, "multiverso-rpg", MultiversoItemSheet, {types:["equipamento","skill","tecnica","classe","subclasse","especie","habilidadeClasse","habilidadeSubclasse","habilidadeEspecie","vantagem"], makeDefault:true, label:"Item Multiverso"});
  foundry.applications.apps.DocumentSheetConfig.registerSheet(Actor, "multiverso-rpg", MultiversoPersonagemSheet, {types:["personagem"], makeDefault:true, label:"Ficha Multiverso"});
  foundry.applications.apps.DocumentSheetConfig.registerSheet(Actor, "multiverso-rpg", MultiversoNPCSheet, {types:["npc"], makeDefault:true, label:"Ficha Rápida de NPC"});
  console.info("Multiverso RPG | Inicializado");
});
